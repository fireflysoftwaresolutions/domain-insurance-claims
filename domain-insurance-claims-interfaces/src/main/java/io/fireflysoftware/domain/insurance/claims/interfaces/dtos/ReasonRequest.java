package io.fireflysoftware.domain.insurance.claims.interfaces.dtos;

/**
 * Optional reason accepted by a closing command. The target status comes from the command, not from this body.
 */
public class ReasonRequest {

    private String statusReason;

    public ReasonRequest() {
    }

    public String getStatusReason() {
        return statusReason;
    }

    public void setStatusReason(String statusReason) {
        this.statusReason = statusReason;
    }
}
